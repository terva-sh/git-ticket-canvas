// Run with node docs/mockups/frames-v1-check.mjs. Uses only synthetic file:// data.
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const snapshot = () => page.evaluate(() => window.mockupSnapshot());
const settle = () => page.waitForFunction(() => !window.mockupSnapshot().pending);
const clickSave = async id => { await page.locator(id).click(); await settle(); };
const reset = async () => { await page.locator('#reset').click(); await page.locator('#readonly').uncheck(); };
try {
  await page.goto(new URL('./frames-v1.html', import.meta.url).href);
  const initial = (await snapshot()).state;
  await page.locator('#x').fill('140');
  await clickSave('#move');
  let data = await snapshot();
  assert.equal(data.undo.length, 1);
  for (const id of ['a', 'b', 'c', 'd']) {
    assert.equal(data.state.cards[id].x, initial.cards[id].x + 100);
    assert.equal(data.state.cards[id].manual, true);
  }
  assert.deepEqual(data.state.cards.e, initial.cards.e);
  await clickSave('#undo');
  assert.deepEqual((await snapshot()).state, initial);
  await clickSave('#redo');
  await clickSave('#external');
  assert.equal(await page.locator('#undo').isDisabled(), true);
  assert.match(await page.locator('#conflict').innerText(), /Card A changed/);
  await page.locator('#fit').click();
  await page.screenshot({ path: '/tmp/frames-v1-conflict.png', fullPage: true });
  await page.locator('#zoom').selectOption('0.8');
  await reset();
  await page.locator('#w').fill('700');
  await clickSave('#resize');
  assert.deepEqual((await snapshot()).state.cards, initial.cards);
  await clickSave('#delete');
  data = await snapshot();
  assert.equal(data.state.frames.delivery, undefined);
  for (const id of ['a', 'b', 'c', 'd']) {
    assert.equal(data.state.cards[id].frame, null);
    assert.equal(data.state.cards[id].x, initial.cards[id].x);
  }
  await clickSave('#undo');
  assert.equal((await snapshot()).state.cards.a.frame, 'delivery');
  await reset();
  await page.locator('#new').focus();
  await page.keyboard.press('Enter');
  assert.match(await page.locator('#capture').innerText(), /2 unassigned cards \(1 hidden\)/);
  await clickSave('#create-save');
  data = await snapshot();
  const frameId = data.state.cards.f.frame;
  assert.ok(frameId);
  assert.equal(data.state.cards.g.frame, frameId);
  assert.equal(data.state.cards.a.frame, 'delivery');
  assert.equal(data.state.cards.f.manual, false);
  await page.locator('[data-kind="card"][data-id="f"]').click();
  await page.locator('#target').selectOption('research');
  await clickSave('#assign');
  assert.equal((await snapshot()).state.cards.f.frame, 'research');
  assert.equal((await snapshot()).state.cards.f.x, initial.cards.f.x);
  await clickSave('#remove');
  assert.equal((await snapshot()).state.cards.f.frame, null);
  await reset();
  await page.locator('#fail').check();
  await page.locator('#x').fill('140');
  await clickSave('#move');
  assert.deepEqual((await snapshot()).state, initial);
  assert.equal((await snapshot()).undo.length, 0);
  assert.match(await page.locator('#status').innerText(), /Save failed/);
  await page.locator('#x').fill('140');
  await page.locator('#move').click();
  await page.keyboard.press('Escape');
  await page.waitForTimeout(700);
  assert.deepEqual((await snapshot()).state, initial);
  await page.locator('#x').fill('140');
  await clickSave('#move');
  await page.locator('#board').selectOption('other');
  assert.equal((await snapshot()).undo.length, 0);
  await page.locator('#board').selectOption('work');
  assert.equal((await snapshot()).undo.length, 1);
  await page.locator('#readonly').check();
  assert.equal(await page.locator('#move').isDisabled(), true);
  assert.equal(await page.locator('#undo').isDisabled(), true);
  await page.locator('[data-kind="card"][data-id="a"]').click();
  assert.equal(await page.locator('#card-move').isDisabled(), true);
  await reset();
  // Real pointer gesture, including an out-of-boundary member and a hidden member.
  const title = page.locator('[data-kind="frame"][data-id="delivery"]');
  let box = await title.boundingBox();
  await page.mouse.move(box.x + 30, box.y + 10);
  await page.mouse.down();
  await page.mouse.move(box.x + 110, box.y + 50, { steps: 4 });
  await page.mouse.up();
  await settle();
  data = await snapshot();
  assert.equal(data.undo.length, 1);
  assert.equal(data.state.cards.c.x, initial.cards.c.x + 100);
  assert.ok(Math.abs(data.state.cards.d.y - initial.cards.d.y - 50) < 0.01);
  await reset();
  box = await title.boundingBox();
  await page.mouse.move(box.x + 30, box.y + 10);
  await page.mouse.down();
  await page.mouse.move(box.x + 110, box.y + 50, { steps: 3 });
  await page.keyboard.press('Escape');
  await page.mouse.up();
  assert.deepEqual((await snapshot()).state, initial);
  // A failed undo keeps its step available for retry.
  await page.locator('#x').fill('140');
  await clickSave('#move');
  await page.locator('#fail').check();
  await clickSave('#undo');
  assert.equal((await snapshot()).undo.length, 1);
  assert.equal((await snapshot()).state.frames.delivery.x, 140);
  await clickSave('#undo');
  assert.deepEqual((await snapshot()).state, initial);
  await reset();
  // A save from the old board cannot land after switching boards.
  await page.locator('#x').fill('140');
  await page.locator('#move').click();
  await page.locator('#board').selectOption('other');
  await page.waitForTimeout(700);
  await page.locator('#board').selectOption('work');
  assert.deepEqual((await snapshot()).state, initial);
  // Real resize gesture does not touch members.
  box = await page.locator('[data-kind="resize"][data-id="delivery"]').boundingBox();
  await page.mouse.move(box.x + 10, box.y + 10);
  await page.mouse.down();
  await page.mouse.move(box.x + 90, box.y + 50, { steps: 3 });
  await page.mouse.up();
  await settle();
  assert.deepEqual((await snapshot()).state.cards, initial.cards);
  assert.ok((await snapshot()).state.frames.delivery.w > initial.frames.delivery.w);
  await reset();
  // Pointer drawing presents a capture review before saving.
  await page.locator('#new').click();
  const scene = await page.locator('#scene').boundingBox();
  await page.mouse.move(scene.x + 32, scene.y + 452);
  await page.mouse.down();
  await page.mouse.move(scene.x + 528, scene.y + 656, { steps: 3 });
  await page.mouse.up();
  assert.match(await page.locator('#capture').innerText(), /2 unassigned cards/);
  await clickSave('#create-save');
  assert.ok((await snapshot()).state.cards.f.frame);
  await reset();
  // Even an overlapping capture leaves existing memberships alone.
  await page.locator('#new').click();
  await page.locator('#y').fill('90');
  await page.locator('#h').fill('750');
  await clickSave('#create-save');
  assert.equal((await snapshot()).state.cards.a.frame, 'delivery');
  assert.equal((await snapshot()).state.cards.g.manual, false);
  await reset();
  await page.locator('#title').fill('Shipping');
  await page.locator('#color').selectOption('#89ad97');
  await clickSave('#appearance');
  assert.equal((await snapshot()).state.frames.delivery.title, 'Shipping');
  await clickSave('#undo');
  assert.deepEqual((await snapshot()).state, initial);
  await reset();
  await page.locator('#x').fill('140');
  await clickSave('#move');
  // An unrelated card edit does not block the frame's history.
  await page.locator('[data-kind="card"][data-id="f"]').click();
  await clickSave('#card-move');
  assert.equal(await page.locator('#undo').isDisabled(), false);
  await clickSave('#undo');
  assert.equal((await snapshot()).state.cards.f.x, initial.cards.f.x + 40);
  // Redo is blocked by a later change to an affected member.
  await page.locator('[data-kind="card"][data-id="a"]').click();
  await clickSave('#card-move');
  assert.equal(await page.locator('#redo').isDisabled(), true);
  await reset();
  await page.locator('#x').fill('140');
  await clickSave('#move');
  box = await page.locator('[data-kind="card"][data-id="a"]').boundingBox();
  await page.mouse.move(box.x + 20, box.y + 20);
  await page.mouse.down();
  await page.mouse.move(box.x + 60, box.y + 20, { steps: 3 });
  await page.mouse.up();
  await settle();
  assert.equal((await snapshot()).state.cards.a.frame, 'delivery');
  assert.equal(await page.locator('#undo').isDisabled(), true);
  await reset();
  await page.locator('#fit').click();
  await page.screenshot({ path: '/tmp/frames-v1-dark.png', fullPage: true });
  await page.locator('#theme').click();
  await page.screenshot({ path: '/tmp/frames-v1-light.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#fit').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: '/tmp/frames-v1-mobile.png', fullPage: true });
  await page.reload();
  assert.equal((await snapshot()).undo.length, 0);
  assert.deepEqual(errors, []);
  console.log('PASS: grouped move, ownership restoration, undo/redo conflict, resize, delete/restore, capture, membership transfer/removal, failure, Escape, boards, read-only, pointer gestures, themes, mobile width, reload.');
  console.log('Screenshots: /tmp/frames-v1-{dark,light,mobile}.png');
} finally {
  await browser.close();
}
